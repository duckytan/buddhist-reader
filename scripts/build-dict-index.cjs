const fs = require('fs')
const path = require('path')

const DICTS_DIR = path.resolve(__dirname, '../public/dicts')
const MANIFEST_PATH = path.join(DICTS_DIR, 'manifest.json')
const OUTPUT_PATH = path.resolve(__dirname, '../src/data/dictIndex.js')

const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'))

const index = {}
const definitions = {} // dictId -> { term -> definition }

for (const dict of manifest) {
  const dictPath = path.join(DICTS_DIR, dict.filename)
  if (!fs.existsSync(dictPath)) {
    console.warn(`Skipping missing dict: ${dict.filename}`)
    continue
  }

  try {
    const data = JSON.parse(fs.readFileSync(dictPath, 'utf8'))
    const defs = {}

    for (const entry of data.entries) {
      const term = entry.term.trim()
      if (term.length < 2) continue
      if (!index[term]) index[term] = []
      if (!index[term].includes(dict.id)) index[term].push(dict.id)

      let definition = entry.definition
      if (Array.isArray(definition)) {
        definition = definition.map(item => {
          if (typeof item === 'string') return item
          if (item && item.c) return item.c
          return ''
        }).join('\n')
      } else if (typeof definition !== 'string') {
        definition = String(definition || '')
      }

      // Truncate to 300 chars for inline embedding
      const summary = definition.length > 300 ? definition.slice(0, 300) + '...' : definition
      defs[term] = summary
    }

    definitions[dict.id] = defs
    console.log(`${dict.id}: ${Object.keys(defs).length} entries`)
  } catch (e) {
    console.warn(`Error reading ${dict.filename}: ${e.message}`)
  }
}

const sortedKeys = Object.keys(index).sort((a, b) => b.length - a.length)

const output = `// Auto-generated by scripts/build-dict-index.cjs
export const dictIndex = ${JSON.stringify(index, null, 0)}

export const dictTerms = ${JSON.stringify(sortedKeys, null, 0)}

export const dictDefinitions = ${JSON.stringify(definitions, null, 0)}
`

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true })
fs.writeFileSync(OUTPUT_PATH, output, 'utf8')

const termCount = Object.keys(index).length
console.log(`dictIndex.js generated: ${termCount} terms, ${Object.keys(definitions).length} dicts`)
console.log(`Total inline definitions: ~${Math.round(JSON.stringify(definitions).length / 1024 / 1024)}MB`)
