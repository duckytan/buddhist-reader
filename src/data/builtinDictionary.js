export function getBuiltinTerm(term) {
  return builtinDictionary.find(d => d.term === term) || null
}

export function searchBuiltinTerms(query) {
  if (!query || query.trim().length === 0) return []
  const q = query.trim()
  return builtinDictionary.filter(d =>
    d.term.includes(q) ||
    d.definition.includes(q) ||
    (d.pinyin && d.pinyin.includes(q))
  )
}

export function getBuiltinTermCount() {
  return builtinDictionary.length
}
